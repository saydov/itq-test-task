package com.github.saydov.documents.enums;

import com.github.saydov.documents.dto.StatusChangeResult;
import com.github.saydov.documents.entity.ApprovalRegistry;

/**
 * Описывает, каким результатом завершилась попытка сменить статус документа.
 *
 * <p>Используется в {@link StatusChangeResult}
 * для описания итога обработки каждого документа в рамках массовой
 * или одиночной смены статуса.</p>
 *
 * @see StatusChangeResult
 */
public enum OperationStatus {

    /**
     * Операция завершилась успешно.
     * Статус документа был изменен на запрашиваемый.
     */
    SUCCESS,

    /**
     * Конфликт при обновлении документа.
     * Возникает, когда документ был параллельно изменен другим потоком
     * и версия записи в базе данных не совпадает с ожидаемой (optimistic locking).
     */
    CONFLICT,

    /**
     * Документ с указанным идентификатором не найден в базе данных.
     * Может возникать, если документ был удален между моментом формирования
     * запроса и его фактической обработкой.
     */
    NOT_FOUND,

    /**
     * Ошибка при взаимодействии с реестром согласований.
     * Сигнализирует о проблеме на стороне {@link ApprovalRegistry},
     * например, при нарушении бизнес-правил согласования.
     */
    REGISTRY_ERROR
}
